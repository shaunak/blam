import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { startLobby } from '../src/lobby.js';
import { mkdir } from 'node:fs/promises';
const key = 'menu-test-key';
const lobby = await startLobby(key);
const origin = (process.env.TEST_CLIENT_URL || `http://127.0.0.1:${lobby.port}`).replace(/\/$/, '');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const context = await browser.newContext();
  // The production Vercel function supplies this header; the browser never receives the key.
  if (!process.env.TEST_CLIENT_URL) await context.route('**/api/session*', async route => {
    const response = await route.fetch({ headers: { ...route.request().headers(), Authorization: `Bearer ${key}` } });
    await route.fulfill({ response });
  });
  const a = await context.newPage();
  await a.goto(origin);
  assert.deepEqual(await a.getByRole('button').allTextContents(), ['Start Game']);
  assert.equal(await a.locator('#crosshair').isVisible(), false, 'menu hides the gameplay HUD');
  const bounds = await a.locator('#start').boundingBox();
  const viewport = a.viewportSize()!;
  assert.ok(bounds && bounds.x < viewport.width / 2 && bounds.y > viewport.height / 2, 'menu actions sit at bottom left');
  const firstFrame = await a.locator('canvas').screenshot();
  await a.waitForTimeout(600);
  assert.notDeepEqual(await a.locator('canvas').screenshot(), firstFrame, 'arena camera orbits in the menu');
  await mkdir('artifacts', { recursive: true });
  await a.screenshot({ path: 'artifacts/main-menu.png' });
  await a.getByRole('button', { name: 'Start Game', exact: true }).click();
  await a.getByRole('heading', { name: 'Copy your invite before playing' }).waitFor({ timeout: 25000 });
  assert.equal(await a.locator('#menu').isVisible(), true, 'creator sees the invite prompt before entering');
  const invite = await a.locator('#invite').inputValue();
  assert.match(new URL(invite).hash, /^#[a-z]+-[a-z]+-[a-z]+$/);
  assert.equal(invite.includes('signal='), false);
  assert.equal(await a.locator('#invite-code').innerText(), new URL(invite).hash.slice(1));
  await a.getByText(/1 \/ 2 players/).waitFor();
  await a.screenshot({ path: 'artifacts/short-invite.png' });
  await a.evaluate("Object.defineProperty(navigator, 'clipboard', { value: { writeText: async text => { window.copiedInvite = text; } }, configurable: true })");
  await a.getByRole('button', { name: 'Copy invite link', exact: true }).click();
  assert.equal(await a.evaluate('window.copiedInvite'), invite);
  assert.equal(await a.locator('#menu').isVisible(), true, 'copying does not start the game');
  await a.getByRole('button', { name: 'Enter arena', exact: true }).click();
  await a.waitForFunction(() => document.pointerLockElement !== null);
  assert.equal(await a.locator('#crosshair').isVisible(), true, 'gameplay HUD returns on entry');
  await a.screenshot({ path: 'artifacts/gameplay-maroon.png' });
  const viewClip = { x: 950, y: 130, width: 250, height: 200 };
  const playingView = await a.screenshot({ clip: viewClip });
  await a.evaluate(() => document.exitPointerLock());
  await a.getByRole('button', { name: 'Resume', exact: true }).waitFor();
  assert.deepEqual(await a.getByRole('button').allTextContents(), ['Copy invite link', 'Resume', 'Quit']);
  assert.equal(await a.locator('#health').isVisible(), true, 'health stays visible while paused');
  assert.equal(await a.locator('#damage').evaluate(el => getComputedStyle(el).visibility), 'visible');
  assert.deepEqual(await a.screenshot({ clip: viewClip }), playingView, 'pause preserves the first-person camera without a screen wash');
  const pause = await a.locator('.card').boundingBox();
  assert.ok(pause && Math.abs(pause.x + pause.width / 2 - viewport.width / 2) < 2 && Math.abs(pause.y + pause.height / 2 - viewport.height / 2) < 2);
  await a.getByRole('button', { name: 'Copy invite link', exact: true }).click();
  await a.getByRole('button', { name: 'Copied', exact: true }).waitFor();
  assert.equal(await a.evaluate('window.copiedInvite'), invite);
  await a.screenshot({ path: 'artifacts/pause-menu.png' });
  const b = await context.newPage();
  await b.setViewportSize({ width: 390, height: 844 });
  await b.addInitScript("Object.defineProperty(Element.prototype, 'requestPointerLock', { value: undefined, configurable: true })");
  await b.goto(invite);
  await b.getByRole('button', { name: 'Join Game', exact: true }).click();
  await b.getByRole('button', { name: 'Menu', exact: true }).waitFor({ timeout: 25000 });
  await a.waitForFunction(() => document.getElementById('players')?.textContent?.startsWith('2 / 2'));
  if (process.env.TEST_CLIENT_URL) for (const page of [a, b]) await page.waitForFunction(() => document.getElementById('connection')?.textContent?.includes('TURN RELAY'), null, { timeout: 10000 });
  await b.getByRole('button', { name: 'Menu', exact: true }).click();
  assert.equal(await b.locator('#invite').inputValue(), invite);
  await b.screenshot({ path: 'artifacts/mobile-invite-menu.png' });
  const third = await context.newPage(); await third.goto(invite);
  await third.getByRole('button', { name: 'Join Game', exact: true }).click();
  await third.getByText(/Room full/).waitFor();
  await third.goto(origin + '/#missing-game-code'); await third.reload();
  await third.getByRole('button', { name: 'Join Game', exact: true }).click();
  await third.getByText(/invite expired/).waitFor();
  assert.equal(await third.getByRole('button', { name: 'Join Game', exact: true }).isEnabled(), true);
  await b.getByRole('button', { name: 'Quit', exact: true }).click();
  await b.getByRole('button', { name: 'Start Game', exact: true }).waitFor();
  await a.waitForFunction(() => document.getElementById('players')?.textContent?.startsWith('1 / 2'));
  await a.bringToFront();
  await a.getByRole('button', { name: 'Resume', exact: true }).click();
  await a.waitForFunction(() => document.pointerLockElement !== null);
  await a.keyboard.down('w'); await a.waitForTimeout(300); await a.keyboard.up('w');
  console.log('PASS: start, creator copy prompt, explicit arena entry, three-word invite, friend join, capacity, invalid invite, desktop capture.');
} finally { await browser.close(); await lobby.close(); }
process.exit(0);
